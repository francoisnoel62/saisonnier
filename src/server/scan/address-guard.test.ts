import { describe, expect, it } from "vitest"

import { isPublicAddress } from "./address-guard"

describe("isPublicAddress", () => {
  it.each([
    "0.0.0.0",
    "0.1.2.3",
    "10.0.0.1",
    "100.64.0.1",
    "100.127.255.255",
    "127.0.0.1",
    "169.254.169.254",
    "172.16.0.1",
    "172.31.255.255",
    "192.0.0.1",
    "192.168.1.1",
    "192.0.2.1",
    "192.88.99.1",
    "198.18.0.1",
    "198.51.100.1",
    "203.0.113.1",
    "224.0.0.1",
    "239.255.255.255",
    "240.0.0.1",
    "255.255.255.255",
    "::",
    "::1",
    "::127.0.0.1",
    "::ffff:127.0.0.1",
    "::ffff:7f00:1",
    "::ffff:8.8.8.8",
    "fc00::1",
    "fd00::1",
    "fe80::1",
    "fe80::1%eth0",
    "ff02::1",
    "2001:db8::1",
    "2001::1",
    "2002:7f00:1::",
    "64:ff9b::7f00:1",
    "3fff::1",
    "not-an-ip",
  ])("refuse %s", (ip) => expect(isPublicAddress(ip)).toBe(false))
  it.each([
    "1.1.1.1",
    "8.8.8.8",
    "100.128.0.1",
    "172.32.0.1",
    "192.169.0.1",
    "2606:4700:4700::1111",
    "2001:4860:4860::8888",
  ])("accepte %s", (ip) => expect(isPublicAddress(ip)).toBe(true))
})
