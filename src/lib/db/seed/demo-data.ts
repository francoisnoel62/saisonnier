// Installe le jeu dans la base, ou le remet à son état initial s'il y est déjà : les entreprises
// sont mises à jour, les offres de démonstration recréées. Rien d'autre n'est touché.
export async function seedDemo(
  db: NodePgDatabase<typeof schema>,
  today: string,
) {
  const demo = demoOffers(today)
  const slugs = [
    ...new Set(demo.flatMap((offer) => offer.occupationSlug ?? [])),
  ]

  await db.transaction(async (tx) => {
    const known = await tx
      .select({ id: occupations.id, slug: occupations.slug })
      .from(occupations)
      .where(inArray(occupations.slug, slugs))
    const occupationIds = new Map(known.map(({ id, slug }) => [slug, id]))
    const missing = slugs.filter((slug) => !occupationIds.has(slug))
    if (missing.length > 0) {
      throw new Error(`Métiers absents du référentiel : ${missing.join(", ")}.`)
    }

    for (const { id, ...fields } of demoCompanies) {
      await tx
        .insert(companies)
        .values({ id, ...fields })
        .onConflictDoUpdate({ target: companies.id, set: fields })
    }

    await tx.delete(offers).where(
      inArray(
        offers.id,
        demo.map((offer) => offer.id),
      ),
    )
    await tx.insert(offers).values(
      demo.map(({ occupationSlug, ...offer }) => ({
        ...offer,
        occupationId: occupationSlug ? occupationIds.get(occupationSlug) : null,
      })),
    )
  })

  return { companies: demoCompanies.length, offers: demo.length }
}
